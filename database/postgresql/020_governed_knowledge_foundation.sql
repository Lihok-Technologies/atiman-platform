    v_manifest_count INTEGER;
    v_matched_count INTEGER;
    v_present_id_count INTEGER;
    v_classified INTEGER;
    v_applicability INTEGER;
BEGIN
    -- 1. the manifest itself must be the ratified 846-identity set
    SELECT count(*) INTO v_manifest_count
      FROM (SELECT split_part(elem, ':', 1)::INTEGER AS template_id,
                   split_part(elem, ':', 2)             AS template_code
              FROM unnest(string_to_array(v_manifest, ',')) AS mf(elem)) m;

    IF v_manifest_count <> 846 THEN
        RAISE EXCEPTION 'M6.3 manifest integrity failure: expected 846 frozen identities, found %',
            v_manifest_count USING ERRCODE = 'check_violation';
    END IF;

    -- The manifest must itself be the ratified identity interval. Expressed as a
    -- contiguity relation over the manifest alone, so no row-range scan and no
    -- range predicate ever participates in classification: if the manifest holds
    -- N distinct ids whose span is exactly N, the ids are necessarily contiguous.
    IF (SELECT max(split_part(elem, ':', 1)::INTEGER)
               - min(split_part(elem, ':', 1)::INTEGER) + 1
          FROM unnest(string_to_array(v_manifest, ',')) AS mf(elem)) <> v_manifest_count THEN
        RAISE EXCEPTION 'M6.3 manifest integrity failure: identities are not the ratified contiguous interval'
            USING ERRCODE = 'check_violation';
    END IF;

    -- 2. how much of the corpus is present?
    --
    -- Two distinct counts are needed, and conflating them was a defect: "how many
    -- frozen identities are present by ID" and "how many match the frozen identity
    -- EXACTLY (id AND code)". A corpus whose rows all sit on frozen manifest IDs
    -- but whose codes do not match produces an exact-match count of zero — which
    -- is indistinguishable from a genuinely absent corpus if only the exact count
    -- is consulted. That let a tampered or systematically mis-coded corpus be
    -- silently treated as absent: the migration reported success, classified
    -- nothing, and backfilled no applicability.
    --
    -- Presence is therefore decided by ID, and exactness by the full identity.
    SELECT count(*) INTO v_present_id_count
      FROM task_templates t
      JOIN (SELECT DISTINCT split_part(elem, ':', 1)::INTEGER AS template_id
              FROM unnest(string_to_array(v_manifest, ',')) AS mf(elem)) m
        ON m.template_id = t.id;

    SELECT count(*) INTO v_matched_count
      FROM task_templates t
      JOIN (SELECT split_part(elem, ':', 1)::INTEGER AS template_id,
                   split_part(elem, ':', 2)             AS template_code
              FROM unnest(string_to_array(v_manifest, ',')) AS mf(elem)) m
        ON m.template_id = t.id
       AND m.template_code = t.template_code;

    -- Genuinely absent corpus: no frozen manifest identity is present at all.
    -- Rows outside the manifest (ids that are not ratified identities) are none of
    -- this migration's business and are tolerated and preserved untouched.
    IF v_present_id_count = 0 THEN
        RAISE NOTICE 'M6.3: reconciled legacy corpus absent - no origin classification performed (allowed no-op)';
        RETURN;
    END IF;

    -- Any frozen identity present without its ratified code is an identity
    -- collision at a reserved identity: presence and identity disagree, so the
    -- migration refuses and rolls back rather than guessing which is right.
    IF v_matched_count <> v_present_id_count THEN
        RAISE EXCEPTION 'M6.3 legacy corpus is INCONSISTENT: % ratified identity id(s) present but only % match the frozen identity exactly. A reserved identity carries a non-ratified code. Refusing to classify.',
            v_present_id_count, v_matched_count USING ERRCODE = 'check_violation';
    END IF;

    IF v_matched_count <> v_manifest_count THEN
        RAISE EXCEPTION 'M6.3 legacy corpus is PARTIAL or INCONSISTENT: % of % ratified identities present. Refusing to partially classify.',
            v_matched_count, v_manifest_count USING ERRCODE = 'check_violation';
    END IF;

    -- 3. classify exactly the reconciled corpus. Idempotent: only unclassified rows
    --    are touched, and content_origin is immutable thereafter, so a second
    --    execution matches zero rows.
    UPDATE task_templates t
       SET content_origin = 'legacy_generated'
     WHERE t.content_origin IS NULL
       AND EXISTS (
           SELECT 1 FROM (SELECT split_part(elem, ':', 1)::INTEGER AS template_id,
                                 split_part(elem, ':', 2)             AS template_code
                            FROM unnest(string_to_array(v_manifest, ',')) AS mf(elem)) m
            WHERE m.template_id = t.id AND m.template_code = t.template_code);
    GET DIAGNOSTICS v_classified = ROW_COUNT;

    -- 4. applicability backfill: the declared Equipment Type is copied verbatim as
    --    the primary anchor. Superseded and retired Equipment Types are NOT
    --    remapped and no taxonomy resolution is applied - declaration is preserved
    --    and governed reconciliation happens later, by humans.
    INSERT INTO task_template_equipment_types (task_template_id, equipment_type_id, is_primary)
    SELECT t.id, t.equipment_type_id, TRUE
      FROM task_templates t
      JOIN (SELECT split_part(elem, ':', 1)::INTEGER AS template_id,
                   split_part(elem, ':', 2)             AS template_code
              FROM unnest(string_to_array(v_manifest, ',')) AS mf(elem)) m
        ON m.template_id = t.id
       AND m.template_code = t.template_code
     WHERE t.equipment_type_id IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM task_template_equipment_types x
            WHERE x.task_template_id = t.id)
    ON CONFLICT (task_template_id, equipment_type_id) DO NOTHING;
    GET DIAGNOSTICS v_applicability = ROW_COUNT;

    RAISE NOTICE 'M6.3: legacy corpus verified (% identities); % row(s) classified; % applicability row(s) inserted',
        v_manifest_count, v_classified, v_applicability;
END
