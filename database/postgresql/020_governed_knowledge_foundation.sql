-- ATM-001 M6.3 — Governed Knowledge Foundation
--
-- Converts the ratified M6.2/M6.3 maintenance-knowledge architecture into schema
-- and governance mechanism. Maintenance Knowledge and Inspection Knowledge are
-- constitutionally distinct Knowledge Foundation domains; they share this one
-- governed knowledge-definition substrate and are distinguished by an explicit,
-- immutable knowledge type that is frozen into each immutable published version.
--
-- Scope (ratified M6.3 minimum):
--   * governed knowledge-type vocabulary + explicit type on definition and version
--   * governed task-family vocabulary (seven ratified families)
--   * governed maintenance-strategy representation (five ratified strategies)
--   * working and frozen Equipment-Type applicability junctions
--   * structured trigger-recommendation model (mechanism / criterion / magnitude /
--     basis / explicit no-fixed-interval) that cannot express a scheduled date
--   * explicit knowledge scope (shared / customer; marketplace non-assignable)
--   * explicit content origin with a fail-closed legacy-corpus manifest
--
-- Explicitly NOT in scope: scheduling, due dates, work orders, labour, materials,
-- inventory, procurement, cost or permit functionality; per-control safety
-- provenance; procedure terminology; a generic knowledge registry; a separate
-- inspection governance stack; marketplace commerce; any AI feature.
--
-- Idempotency: scripts/migrate-postgres.js reapplies every migration on every run
-- and keeps no applied-migrations ledger, so this file must be safe to execute
-- repeatedly. All DDL is guarded (CREATE ... IF NOT EXISTS / ADD COLUMN IF NOT
-- EXISTS / guarded DO blocks / DROP TRIGGER IF EXISTS before CREATE), all seeds
-- use ON CONFLICT DO NOTHING, and every backfill is written so that a second run
-- matches zero rows.
--
-- Forward-only: there is no down-migration. Every change here is additive and no
-- existing constraint is dropped or weakened.
--
-- Legacy manifest provenance: the identity set below is frozen from the accepted
-- M6.1 reconciliation artifact
--   docs/research/m6r1/maintenance-procedure-reconciliation.jsonl
-- (846 records, sha256 prefix 8e0e32e522b6c519). It is an explicit manifest, not a
-- timestamp or a heuristic predicate. A future revision of the corpus requires a
-- NEW forward migration; this file must never be edited to accommodate one.

-- ===========================================================================
-- PART 1 — governed knowledge vocabularies
-- ===========================================================================

-- Knowledge type: which constitutional Knowledge Foundation domain this governed
-- definition belongs to. A reference table, not a CHECK constraint, because the
-- Constitution enumerates further domains and adding one must be a governed data
-- action rather than a schema migration.
CREATE TABLE IF NOT EXISTS knowledge_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    type_code VARCHAR(50) NOT NULL,
    type_name VARCHAR(200) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_knowledge_types_type_code UNIQUE (type_code)
);

-- Only the semantic types this substrate currently carries are seeded. Further
-- constitutional domains are added as governed data when they adopt this substrate.
