-- ---------------------------------------------------------------------------
-- 9.1 content_origin is immutable once established.
-- ---------------------------------------------------------------------------
-- A NULL origin may be classified exactly once. Thereafter it can never change,
-- which is what (a) keeps legacy provenance permanently traceable and (b) makes
-- the classification backfill idempotent, because a transformed candidate always
-- retains legacy_generated and is therefore never re-matched by a NULL predicate.

CREATE OR REPLACE FUNCTION task_template_origin_immutability_check()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.content_origin IS NOT NULL
       AND NEW.content_origin IS DISTINCT FROM OLD.content_origin THEN
        RAISE EXCEPTION 'task_template % content_origin is immutable once established (was %, attempted %)',
            OLD.id, OLD.content_origin, NEW.content_origin
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

