-- ---------------------------------------------------------------------------
-- 9.3 Publication admission for an immutable task-template version.
-- ---------------------------------------------------------------------------
-- Cross-row invariants that a CHECK cannot express. Deferred to COMMIT so that a
-- publisher may insert the version, its step versions, its frozen evidence and its
-- applicability inside one transaction and be judged on the final state — the
-- established 019 idiom. Enforced in the database so that a direct SQL write
-- cannot bypass admission.

CREATE OR REPLACE FUNCTION task_template_version_publication_admission()
RETURNS TRIGGER AS $$
DECLARE
    parent_origin TEXT;
    parent_cleared BOOLEAN;
    evidence_count INTEGER;
    applicability_count INTEGER;
    safety_control_count INTEGER;
BEGIN
    -- (a) origin: only authored knowledge, or legacy knowledge with recorded
    --     accountable clearance, may reach a governed version.
    SELECT t.content_origin,
           (t.legacy_clearance_by_user_id IS NOT NULL AND t.legacy_clearance_at IS NOT NULL)
      INTO parent_origin, parent_cleared
      FROM task_templates t
     WHERE t.id = NEW.task_template_id;

    IF parent_origin IS NULL THEN
        RAISE EXCEPTION 'task_template_version % cannot be governed: parent task_template % has no established content_origin',
            NEW.id, NEW.task_template_id USING ERRCODE = 'check_violation';
    END IF;

    IF parent_origin = 'legacy_generated' AND NOT COALESCE(parent_cleared, FALSE) THEN
        RAISE EXCEPTION 'task_template_version % cannot be governed: legacy_generated task_template % has no recorded accountable clearance',
            NEW.id, NEW.task_template_id USING ERRCODE = 'check_violation';
    END IF;

    -- (b) frozen evidence: the version itself or one of its step versions must
    --     carry provenance.
    SELECT count(*) INTO evidence_count
      FROM knowledge_template_version_evidence e
     WHERE e.task_template_version_id = NEW.id
        OR e.task_template_step_version_id IN (
               SELECT sv.id FROM task_template_step_versions sv
                WHERE sv.task_template_version_id = NEW.id);

    IF evidence_count = 0 THEN
        RAISE EXCEPTION 'task_template_version % cannot be governed: no frozen evidence row exists',
            NEW.id USING ERRCODE = 'check_violation';
    END IF;

    -- (c) safety review: when the version carries safety controls the reviewer must
    --     have attested that controls are defined. This is a single attestation over
    --     the control set; it does NOT assert per-control provenance, which is
    --     deliberately unsupported.
    SELECT count(*) INTO safety_control_count
      FROM task_template_safety_control_versions scv
     WHERE scv.task_template_version_id = NEW.id;

    IF safety_control_count > 0 AND NEW.safety_review_state IS DISTINCT FROM 'reviewed_controls_defined' THEN
        RAISE EXCEPTION 'task_template_version % carries % safety control(s) but safety_review_state is %; reviewer attestation over defined controls is required',
            NEW.id, safety_control_count, COALESCE(NEW.safety_review_state, 'NULL')
            USING ERRCODE = 'check_violation';
    END IF;

    -- (d) applicability: a governed version must declare at least one Equipment Type.
    SELECT count(*) INTO applicability_count
      FROM task_template_version_equipment_types x
     WHERE x.task_template_version_id = NEW.id;

    IF applicability_count = 0 THEN
        RAISE EXCEPTION 'task_template_version % cannot be governed: no Equipment Type applicability is recorded',
            NEW.id USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_task_template_version_publication_admission ON task_template_versions;

CREATE CONSTRAINT TRIGGER trg_task_template_version_publication_admission
    AFTER INSERT OR UPDATE ON task_template_versions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION task_template_version_publication_admission();

-- ---------------------------------------------------------------------------
-- 9.4 Knowledge Pack ownership scope.
-- ---------------------------------------------------------------------------
-- A governed pack version must record an explicit scope, and the pack identity
-- must have established its ownership before any governed version exists.
--
-- R1 REMEDIATION: a Pack version's scope is a SNAPSHOT of the ownership its Pack
-- already declared, so the two can never legitimately disagree — at any lifecycle
-- state, not only at publication. The consistency check below therefore runs
-- unconditionally (before the governed-state early return), because an
-- inconsistent draft snapshot could otherwise be carried into a governed state,
-- and because a version must never assert an ownership its Pack does not have.

CREATE OR REPLACE FUNCTION knowledge_pack_version_scope_governed_check()
RETURNS TRIGGER AS $$
DECLARE
    pack_scope TEXT;
BEGIN
    SELECT p.knowledge_scope INTO pack_scope
      FROM knowledge_packs p WHERE p.id = NEW.knowledge_pack_id;

    -- The snapshot must equal the Pack's established ownership. Written as a
    -- null-safe comparison so that an unscoped Pack accepts only an unscoped
    -- draft, and a scoped Pack never accepts an unscoped or different snapshot.
    IF NEW.knowledge_scope IS DISTINCT FROM pack_scope THEN
        RAISE EXCEPTION 'knowledge_pack_version % declares knowledge scope % but its pack % has established %',
            NEW.id, COALESCE(NEW.knowledge_scope, 'NULL'), NEW.knowledge_pack_id,
            COALESCE(pack_scope, 'no scope')
            USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.lifecycle_state NOT IN ('published','superseded','retired') THEN
        RETURN NULL;
    END IF;

    IF NEW.knowledge_scope IS NULL THEN
        RAISE EXCEPTION 'knowledge_pack_version % cannot be governed: no explicit knowledge scope',
            NEW.id USING ERRCODE = 'check_violation';
    END IF;

    IF pack_scope IS NULL THEN
        RAISE EXCEPTION 'knowledge_pack_version % cannot be governed: pack % has no established ownership scope',
            NEW.id, NEW.knowledge_pack_id USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_knowledge_pack_version_scope_governed ON knowledge_pack_versions;

CREATE CONSTRAINT TRIGGER trg_knowledge_pack_version_scope_governed
    AFTER INSERT OR UPDATE ON knowledge_pack_versions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION knowledge_pack_version_scope_governed_check();

-- ---------------------------------------------------------------------------
-- 9.5 Pack membership scope compatibility.
-- ---------------------------------------------------------------------------
-- Shared packs may contain only shared knowledge. Customer packs may contain
-- shared knowledge plus customer knowledge of the same organization. Marketplace
-- packs cannot exist under the assignability guard.
--
-- R1 REMEDIATION: the rule above was too permissive and disagreed with the
-- application service. ATM-001 M6.3 ratifies a single member rule — a Pack member
-- must be globally applicable (shared) knowledge. A customer-owned Pack may
-- exist (it is a tenant's curated pack identity), but customer ownership of the
-- Pack does NOT authorize customer-scoped member knowledge during M6.3:
--
--   shared Pack   -> shared member    permitted
--   customer Pack -> shared member    permitted
--   customer Pack -> customer member  REFUSED
--   marketplace                       not assignable, hence unreachable
--
-- Storage now enforces the same rule the service enforces, so a direct SQL write
-- can no longer compose a pack the service would refuse. The tighter rule is
-- adopted by storage; the service is not weakened.

CREATE OR REPLACE FUNCTION knowledge_pack_membership_scope_compatibility()
RETURNS TRIGGER AS $$
DECLARE
    pack_scope TEXT;
    member_scope TEXT;
BEGIN
    SELECT v.knowledge_scope
      INTO pack_scope
      FROM knowledge_pack_versions v
     WHERE v.id = NEW.knowledge_pack_version_id;

    SELECT tv.knowledge_scope
      INTO member_scope
      FROM task_template_versions tv
     WHERE tv.id = NEW.task_template_version_id;

    IF pack_scope IS NULL OR member_scope IS NULL THEN
        RAISE EXCEPTION 'pack membership requires explicit knowledge scope on both the pack version and the member version'
            USING ERRCODE = 'check_violation';
    END IF;

    IF member_scope <> 'shared' THEN
        RAISE EXCEPTION 'pack version % may not contain % knowledge: an M6.3 pack member must be globally applicable (shared) knowledge',
            NEW.knowledge_pack_version_id, member_scope USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

