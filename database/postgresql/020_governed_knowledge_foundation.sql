-- Task family: what kind of action the knowledge prescribes. Orthogonal to
-- knowledge type and never inferred from it. A reference table because ATM-013C2
-- §1.2 explicitly permits additional families where engineering evidence supports
-- them, so growth must be a data action.
CREATE TABLE IF NOT EXISTS task_families (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    family_code VARCHAR(50) NOT NULL,
    family_name VARCHAR(200) NOT NULL,
    description TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
