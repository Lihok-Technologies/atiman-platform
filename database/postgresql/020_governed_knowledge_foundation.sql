-- ---------------------------------------------------------------------------
-- 9.2 Legacy clearance is a separate, accountable, write-once event.
-- ---------------------------------------------------------------------------
-- Clearance never mutates origin; it records that an accountable human accepted
-- responsibility for transforming legacy-generated material into governed
-- knowledge. The attribution FKs are RESTRICT so accountability cannot evaporate.

CREATE OR REPLACE FUNCTION task_template_legacy_clearance_guard()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.legacy_clearance_by_user_id IS NOT NULL
       AND OLD.legacy_clearance_by_user_id IS NULL THEN
        -- first clearance: the record must still be traceably legacy-generated
        IF NEW.content_origin IS DISTINCT FROM 'legacy_generated' THEN
            RAISE EXCEPTION 'task_template % clearance requires content_origin = legacy_generated', OLD.id
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF OLD.legacy_clearance_by_user_id IS NOT NULL
          AND NEW.legacy_clearance_by_user_id IS DISTINCT FROM OLD.legacy_clearance_by_user_id THEN
        -- clearance is write-once: accountable attribution is never reassigned
        RAISE EXCEPTION 'task_template % legacy clearance is write-once', OLD.id
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

